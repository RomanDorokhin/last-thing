export function getEnding(morality: number, choices: Record<string, string>) {
  const copiedEvidence = choices['evidence_copy'] === 'B';
  const savedPartner = choices['partner_wait'] === 'B';

  if (copiedEvidence && (morality >= 50 || savedPartner)) {
    return ENDINGS.rightThing;
  }
  if (morality >= 40 || savedPartner) {
    return ENDINGS.ghost;
  }
  return ENDINGS.clean;
}
